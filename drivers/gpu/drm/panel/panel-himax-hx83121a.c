static int hx83121a_off(struct hx83121a_panel *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 120);

	return dsi_ctx.accum_err;
}

static int hx83121a_prepare(struct drm_panel *panel)
{
	struct hx83121a_panel *ctx = to_hx83121a_panel(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = regulator_bulk_enable(ARRAY_SIZE(hx83121a_supplies), ctx->supplies);
	if (ret < 0) {
		dev_err(dev, "Failed to enable regulators: %d\n", ret);
		return ret;
	}

	hx83121a_reset(ctx);

	ret = hx83121a_on(ctx);
	if (ret < 0) {
		dev_err(dev, "Failed to initialize panel: %d\n", ret);
		gpiod_set_value_cansleep(ctx->reset_gpio, 1);
		regulator_bulk_disable(ARRAY_SIZE(hx83121a_supplies), ctx->supplies);
		return ret;
	}

	return 0;
}

static int hx83121a_enable(struct drm_panel *panel)
{
	msleep(20);
	return 0;
}

static int hx83121a_unprepare(struct drm_panel *panel)
{
	struct hx83121a_panel *ctx = to_hx83121a_panel(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = hx83121a_off(ctx);
	if (ret < 0)
		dev_err(dev, "Failed to un-initialize panel: %d\n", ret);

	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(1000, 2000);
	regulator_bulk_disable(ARRAY_SIZE(hx83121a_supplies), ctx->supplies);

	return 0;
}

